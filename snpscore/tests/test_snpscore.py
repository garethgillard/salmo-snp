def test_formats_give_the_same_sites(tmp_path):
    sites = [s for s in fixture_sites(chrom="25") if len(s[3]) == 1 and len(s[4]) == 1][:5]
    files = {
        "SYNTHETIC.vcf": "##fileformat=VCFv4.2\n#CHROM\tPOS\tID\tREF\tALT\n" + "".join("\t".join(s) + "\n" for s in sites),
        "SYNTHETIC.tsv": SYNTHETIC + "CHR\tBP\tSNP\tA2\tA1\tbeta\n" + "".join(f"{c}\t{p}\t{i}\t{r}\t{a}\t0.1\n" for c, p, i, r, a in sites),
        "SYNTHETIC.bim": "".join(f"{c}\t{i}\t0\t{p}\t{a}\t{r}\n" for c, p, i, r, a in sites),
        "SYNTHETIC_manifest.csv": SYNTHETIC.replace("#", "") + "[Heading]\nDescriptor File Name,SYNTHETIC.bpm\n[Assay]\n"
            "IlmnID,Name,IlmnStrand,SNP,Chr,MapInfo\n" + "".join(f"{i}-0_T_F,{i},TOP,[{r}/{a}],{c},{p}\n" for c, p, i, r, a in sites)
            + "[Controls]\n0027630314,Staining,Red,DNP (High)\n",
        "SYNTHETIC_annotation.csv": "#%SYNTHETIC test data generated by tests/test_snpscore.py\n#%chip_type=SYNTHETIC\n"
            '"Probe Set ID","Chromosome","Physical Position","Allele A","Allele B"\n'
            + "".join(f'"{i}","{c}","{p}","{r}","{a}"\n' for c, p, i, r, a in sites),
        "SYNTHETIC_paste.txt": "".join(f"{c} {p}  {r} {a}\n" for c, p, i, r, a in sites),
    }
    expected = [tuple(s) for s in sites]
    con = duckdb.connect()
    for name, text in files.items():
        path = tmp_path / name
        path.write_text(text)
        layout = detect(path)
        got = con.execute(f"SELECT chrom, pos, {'NULL' if 'paste' in name else 'id'}, ref, alt FROM ({source(path, layout)})").fetchall()
        want = [(c, p, None if "paste" in name else i, r, a) for c, p, i, r, a in expected]
        assert got == want, (name, layout["format"])
        assert not any(n and n.startswith("in_") and n[3:].lower() in RESERVED for n in layout["names"])
    gz = tmp_path / "SYNTHETIC.map.gz"
    with gzip.open(gz, "wt") as f:
        f.write("".join(f"{c} {i} 0 {p}\n" for c, p, i, r, a in sites))
    assert con.execute(f"SELECT chrom, pos, id FROM ({source(gz, detect(gz))})").fetchall() == [s[:3] for s in expected]
    bad = tmp_path / "SYNTHETIC_bad.tsv"
    bad.write_text(SYNTHETIC + "marker\tlocation\nx\ty\n")
    with pytest.raises(InputError, match="Accepted"):
        detect(bad)


def test_damaged_and_ambiguous_files(release, tmp_path):
    con = duckdb.connect()

    def rows(name, data):
        path = tmp_path / name
        if isinstance(data, bytes):
            path.write_bytes(data)
        else:
            path.write_text(data)
        return con.execute(f"SELECT * FROM ({source(path, detect(path))})").fetchall()

    # A '#CHROM' header that isn't VCF's own is read by its names; BED gives pos = end, only for 1-bp intervals
    assert rows("SYNTHETIC_hash.tsv", "#CHROM\tPOS\tREF\tALT\n25\t28996360\tC\tT\n") == [("25", "28996360", "C", "T")]
    assert rows("SYNTHETIC.bed", "track name=SYNTHETIC\n25\t28996359\t28996360\trs1\n25\t100\t200\tregion\n") == [
        ("25", "28996360", "rs1"), ("25", None, "region")]
    # Damaged or odd files give a fixed message, not a traceback; a very long line is not read whole
    damaged = bytearray(gzip.compress(b"chrom\tpos\n" + b"25\t28996360\n" * 1000))
    damaged[30] ^= 0xFF
    for name, data in [("SYNTHETIC.tsv.gz", bytes(damaged)), ("SYNTHETIC_assay.csv", "[Heading]\n[Assay]"),
                       ("SYNTHETIC_long.txt.gz", gzip.compress(b"A" * (3 << 20)))]:
        with pytest.raises(InputError):
            rows(name, data)
    # Positions must be whole numbers: 28996360.5 and 2.8996360e7 are rejected, not rounded
    f = tmp_path / "SYNTHETIC_decimal.tsv"
    f.write_text(SYNTHETIC + "chrom\tpos\n25\t28996360.5\n25\t2.8996360e7\n25\t28996360\n")
    assert report(annotate(f, release, tmp_path / "decimal.parquet"))["rejected"] == {"bad_pos": 2}


