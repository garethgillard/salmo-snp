def read(path):
    rel = duckdb.sql(f"SELECT * FROM read_parquet('{path}')")
    return [dict(zip(rel.columns, row)) for row in rel.fetchall()]


def fixture_sites(n=None, chrom=None):
    """(chrom, pos, id, ref, alt) of fixture VCF sites, optionally on one chromosome."""
    rows = [line.split("\t")[:5] for line in (FIXTURE / "snps.vcf").read_text().splitlines() if not line.startswith("#")]
