def test_sandbox(tmp_path):
    job = tmp_path / "job"
    job.mkdir()
    link = Path("/tmp") / f"snpscore-test-{tmp_path.name}"
    link.symlink_to(job)
    try:
        (job / "sub").mkdir()
        con = connect([FIXTURE, job / "sub"], link)  # a symlinked job dir, as /tmp is on macOS, and a folder inside it
        con.execute(f"COPY (SELECT 1 AS a) TO '{job.resolve() / 'x.parquet'}' (FORMAT parquet)")
        assert con.execute(f"SELECT a FROM read_parquet('{job.resolve() / 'x.parquet'}')").fetchone() == (1,)
        for sql in ["SELECT * FROM read_csv('/etc/hosts')", "SELECT * FROM read_csv('https://salmobase.org/x.csv')",
                    "INSTALL httpfs", "SET enable_external_access = true", "COPY (SELECT 1) TO '/tmp/x.csv'"]:
            with pytest.raises(duckdb.Error):
                con.execute(sql)
        # Spills go to the write folder; a read-only connection never spills (DuckDB's default is <cwd>/.tmp)
        assert con.execute("SELECT current_setting('temp_directory')").fetchone()[0] == str(job.resolve())
        assert connect([job]).execute("SELECT current_setting('temp_directory')").fetchone()[0] == ""
    finally:
        link.unlink()


