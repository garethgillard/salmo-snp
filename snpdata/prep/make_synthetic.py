"""SYNTHETIC test and demo data (ROADMAP 'Synthetic data'). Every file name contains SYNTHETIC and every text file
starts with '# SYNTHETIC test data generated by prep/make_synthetic.py <command> (seed N): not real results'.
Built from public sites only; no breeder data is used or imitated. Run in snpdata/.

    python prep/make_synthetic.py chip                   # dev scale: data/synthetic/chip_demo_SYNTHETIC.tsv
    python prep/make_synthetic.py chip --scale fixture   # tests/fixture/synthetic/chip_demo_SYNTHETIC.tsv
    python prep/make_synthetic.py gwas                   # data/synthetic/gwas_maturation_SYNTHETIC.* (+ _truth.tsv)

`snpdata build` copies the chip into release/<v>/demo/ (layers.yaml 'demo'), where the portal offers it as the demo
chip for chip comparison. Later commands (gwas, molqtl) are added here too.
"""
import argparse
import random
from pathlib import Path

import duckdb

SEED = 42
VCF = "12_samples_genotype_filtered_on_504.vcf.gz"
SCALES = {  # public sites, output folder, planted gaps, gap length (bp)
    "dev": ("data/raw/" + VCF, "data/synthetic", 3, 1_500_000),
    "fixture": ("tests/fixture/" + VCF, "tests/fixture/synthetic", 1, 1_100_000),
}


def header(command, seed):
    return f"# SYNTHETIC test data generated by prep/make_synthetic.py {command} (seed {seed}): not real results\n"


def chip(vcf, out_dir, n_gaps, gap_bp, every=30, seed=SEED):
    """A demo chip: every `every`-th public site in genome order, minus the sites in `n_gaps` planted gaps of gap_bp
    (one per chromosome, chromosomes and starts drawn with the seed; each gap starts at a public site and covers at
    least 2 * every public sites, so the pool has SNPs to fill it). Writes chip_demo_SYNTHETIC.tsv (chrom, pos, id)."""
    con = duckdb.connect()
    con.execute(f"""CREATE TABLE sites AS SELECT chrom, pos::BIGINT AS pos, id FROM read_csv('{vcf}', delim='\t',
                    header=false, comment='#', all_varchar=true, names=['chrom', 'pos', 'id'], null_padding=true)
                    ORDER BY try_cast(chrom AS INTEGER), chrom, pos""")
    rng = random.Random(seed)
    # candidate gap starts: sites with at least 2 * every sites in the next gap_bp and room before the chromosome's last site
    starts = con.execute(f"""SELECT chrom, pos FROM (
        SELECT chrom, pos, count(*) OVER (PARTITION BY chrom ORDER BY pos RANGE BETWEEN CURRENT ROW AND {gap_bp} FOLLOWING) AS n,
               max(pos) OVER (PARTITION BY chrom) AS last FROM sites)
        WHERE n >= {2 * every} AND pos + {gap_bp} < last ORDER BY try_cast(chrom AS INTEGER), chrom, pos""").fetchall()
    chroms = sorted({c for c, _ in starts}, key=lambda c: (len(c), c))
    gaps = []
    for c in rng.sample(chroms, min(n_gaps, len(chroms))):
        start = rng.choice([p for ch, p in starts if ch == c])
        gaps.append((c, start - 1, start - 1 + gap_bp))  # BED-style: sites with start < pos <= end are removed
    gaps.sort(key=lambda g: (int(g[0]) if g[0].isdigit() else 0, g[1]))
    planted = " OR ".join(f"(chrom = '{c}' AND pos > {s} AND pos <= {e})" for c, s, e in gaps) or "false"
    rows = con.execute(f"""SELECT chrom, pos, coalesce(nullif(id, '.'), chrom || ':' || pos) FROM (
                               SELECT *, row_number() OVER (ORDER BY try_cast(chrom AS INTEGER), chrom, pos) AS k FROM sites)
                           WHERE k % {every} = 0 AND NOT ({planted}) ORDER BY k""").fetchall()
    out = Path(out_dir) / "chip_demo_SYNTHETIC.tsv"
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w") as f:
        f.write(header("chip", seed))
        f.write(f"# every {every}th public site of {Path(vcf).name}; planted gaps (BED): "
                + ", ".join(f"{c}:{s}-{e}" for c, s, e in gaps) + "\n")
        f.write("chrom\tpos\tid\n" + "".join(f"{c}\t{p}\t{i}\n" for c, p, i in rows))
    print(f"{out}: {len(rows)} SNPs, planted gaps {gaps}")
    return out, gaps


# ---- gwas (P1.6b): synthetic summary statistics over public sites, with planted causal SNPs ----

GWAS_LOCI = [  # (label, chrom, causal pos, target p, scales); every causal SNP is a public 12-fish site
    ("a_vgll3", "25", 28996360, 1e-30, ("fixture", "dev")),  # vgll3 Met54Thr (CDS)
    ("b_nae1", "26", 14991610, 1e-9, ("fixture", "dev")),    # cmtm4 intron in a Gonad Active_enhancer peak, 60 kb from nae1
    ("c_chr21", "21", 32921238, 1e-12, ("fixture", "dev")),  # akap11 intron, Active_enhancer in Brain and Gonad
    ("d_decoy", "1", 110987765, 1e-10, ("fixture", "dev")),  # LORe 1-18, intergenic, tier 4: the only public site in 110-111 Mb
    ("e_six6", "9", 23838080, 1e-15, ("dev",)),               # six6: the public site nearest the published lead 9:23837450
]
GWAS_N, NULL_SD, EVERY = 1500, 1.05 ** 0.5, 8  # sample size; null z ~ N(0, sqrt(1.05)); dev: every 8th site genome-wide
# LD mimic: r_j = u_j exp(-max(0, |d| - BLOCK L) / L) with u_j ~ U(U_MIN, 1); the ROADMAP's plain z_c exp(-|d|/L) u_j
# plus independent noise leaves one-SNP credible sets at p 1e-30, so linked SNPs share the causal SNP's noise as under LD
U_MIN, BLOCK = 0.95, 0.25
CHI2_MEDIAN = 0.4549364231195724


def gwas(vcf, out_dir, scale="dev", seed=SEED):
    """Synthetic GWAS of 'maturation' over public sites (fixture: every fixture site; dev: every 8th site plus all sites
    within 1 Mb of a causal SNP, about 200K). Null z ~ N(0, sqrt(1.05)); the causal SNP has z = z_c + e (z_c from the
    target p, random sign) and LD is mimicked by distance decay: z_j = r_j z + sqrt(1 - r_j^2) e_j with
    r_j = u_j exp(-max(0, |d| - L/4) / L), u_j ~ U(0.95, 1) and L ~ U(20, 80) kb per locus (a block of L/4 either side,
    then decay); se = 1 / sqrt(2 N af (1 - af)) (standardised trait), beta = z se.
    Writes gwas_maturation_SYNTHETIC.tsv (chrom, pos, id, ref, alt, beta, se, p, af, n; beta per alt allele), .fastGWA
    (every 3rd row with A1 = ref), .glm.linear (PLINK2; every 4th row with A1 = REF), _ponly.tsv (chrom, pos, id, p; the
    vgll3 causal SNP has p '1e-400') and _truth.tsv (causal SNPs with z_c, L, realised z and p; lambda_gc of the file
    as written, and lambda_null)."""
    import math
    from statistics import NormalDist, median
    loci = [x for x in GWAS_LOCI if scale in x[4]]
    near = " OR ".join(f"(chrom = '{c}' AND abs(pos - {p}) <= 1000000)" for _, c, p, _, _ in loci)
    causal = " OR ".join(f"(chrom = '{c}' AND pos = {p})" for _, c, p, _, _ in loci)
    con = duckdb.connect()
    sites = con.execute(f"""SELECT chrom, pos, id, ref, alt, af FROM (
        SELECT *, row_number() OVER (ORDER BY try_cast(chrom AS INTEGER), chrom, pos) AS k FROM (
            SELECT chrom, pos::BIGINT AS pos, id, ref, alt, try_cast(regexp_extract(info, 'AF=([0-9.eE-]+)', 1) AS DOUBLE) AS af
            FROM read_csv('{vcf}', delim='\t', header=false, comment='#', all_varchar=true, null_padding=true,
                          names=['chrom', 'pos', 'id', 'ref', 'alt', 'qual', 'filter', 'info'])
            WHERE chrom SIMILAR TO '[0-9]+' AND NOT contains(alt, ',')))
        WHERE ({causal}) OR (af BETWEEN 0.01 AND 0.99 AND ({'true' if scale == 'fixture' else f'k % {EVERY} = 0 OR {near}'}))
        ORDER BY try_cast(chrom AS INTEGER), pos""").fetchall()
    rng = random.Random(seed)
    planted = []
    for label, chrom, pos, p, _ in loci:
        z_c = rng.choice((1, -1)) * -NormalDist().inv_cdf(p / 2)
        planted.append({"label": label, "chrom": chrom, "pos": pos, "p_target": p, "z_c": z_c, "L": round(rng.uniform(20e3, 80e3)),
                        "z": z_c + rng.gauss(0, NULL_SD)})  # the causal SNP's z as observed
    rows, truth = [], {}
    for chrom, pos, sid, ref, alt, af in sites:
        signal, r = 0.0, 0.0
        for c in planted:
            d = abs(pos - c["pos"])
            if c["chrom"] == chrom and d <= 10 * c["L"]:
                r = math.exp(-max(0, d - BLOCK * c["L"]) / c["L"]) * (1.0 if d == 0 else rng.uniform(U_MIN, 1))
                signal += r * c["z"]
        z = signal + math.sqrt(1 - r * r) * rng.gauss(0, NULL_SD) if r < 1 else signal
        se = 1 / math.sqrt(2 * GWAS_N * af * (1 - af))
        beta_s, se_s, p_s = f"{z * se:.6g}", f"{se:.6g}", f"{math.erfc(abs(z) / math.sqrt(2)):.4g}"
        rows.append((chrom, pos, sid, ref, alt, beta_s, se_s, p_s, f"{af:.4g}", signal))
        for c in planted:
            if (chrom, pos) == (c["chrom"], c["pos"]):
                truth[c["label"]] = (sid, ref, alt, z, p_s)
    z2 = [(float(r[5]) / float(r[6])) ** 2 for r in rows]
    lam = median(z2) / CHI2_MEDIAN
    lam_null = median(x for x, r in zip(z2, rows) if r[9] == 0) / CHI2_MEDIAN
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    stem, head = out / "gwas_maturation_SYNTHETIC", header("gwas", seed)
    note = f"# {len(rows)} public sites of {Path(vcf).name}, scale {scale}; planted loci and lambda in gwas_maturation_SYNTHETIC_truth.tsv\n"
    with open(f"{stem}.tsv", "w") as f:
        f.write(head + note + "# beta is per copy of the alt allele; standardised trait, n = 1500\n")
        f.write("chrom\tpos\tid\tref\talt\tbeta\tse\tp\taf\tn\n")
        f.writelines(f"{c}\t{p}\t{i}\t{r}\t{a}\t{b}\t{s}\t{pv}\t{af}\t{GWAS_N}\n" for c, p, i, r, a, b, s, pv, af, _ in rows)
    with open(f"{stem}.fastGWA", "w") as f:  # GCTA-fastGWA layout; every 3rd row reports the ref allele as A1
        f.write(head + note + "CHR\tSNP\tPOS\tA1\tA2\tN\tAF1\tBETA\tSE\tP\n")
        for k, (c, p, i, r, a, b, s, pv, af, _) in enumerate(rows):
            if k % 3 == 2:
                r, a, b, af = a, r, _neg(b), f"{1 - float(af):.4g}"
            f.write(f"{c}\t{i}\t{p}\t{a}\t{r}\t{GWAS_N}\t{af}\t{b}\t{s}\t{pv}\n")
    with open(f"{stem}.glm.linear", "w") as f:  # PLINK2 --glm layout; every 4th row tests the REF allele (A1 = REF)
        f.write(head + note + "#CHROM\tPOS\tID\tREF\tALT\tA1\tA1_FREQ\tTEST\tOBS_CT\tBETA\tSE\tT_STAT\tP\tERRCODE\n")
        for k, (c, p, i, r, a, b, s, pv, af, _) in enumerate(rows):
            a1, freq = (r, f"{1 - float(af):.4g}") if k % 4 == 3 else (a, af)
            beta = _neg(b) if k % 4 == 3 else b
            f.write(f"{c}\t{p}\t{i}\t{r}\t{a}\t{a1}\t{freq}\tADD\t{GWAS_N}\t{beta}\t{s}\t{float(beta) / float(s):.5g}\t{pv}\t.\n")
    vgll3 = (planted[0]["chrom"], planted[0]["pos"])
    with open(f"{stem}_ponly.tsv", "w") as f:  # p values only (no alleles or effects); one p beyond DOUBLE's range
        f.write(head + note + "chrom\tpos\tid\tp\n")
        f.writelines(f"{c}\t{p}\t{i}\t{'1e-400' if (c, p) == vgll3 else pv}\n" for c, p, i, _, _, _, _, pv, _, _ in rows)
    with open(f"{stem}_truth.tsv", "w") as f:
        f.write(head + f"# lambda_gc: {lam:.4f} (median z^2 / 0.4549 over all {len(rows)} rows, z = beta / se as written)\n"
                f"# lambda_null: {lam_null:.4f} (rows more than 10 L from every causal SNP)\n")
        f.write("locus\tchrom\tpos\tid\tref\talt\tz_c\tL\tz\tp\tp_target\n")
        for c in planted:
            sid, ref, alt, z, p_s = truth[c["label"]]
            f.write(f"{c['label']}\t{c['chrom']}\t{c['pos']}\t{sid}\t{ref}\t{alt}\t{c['z_c']:.4f}\t{c['L']}\t{z:.4f}\t{p_s}\t{c['p_target']:g}\n")
    print(f"{stem}.tsv (+ .fastGWA, .glm.linear, _ponly.tsv, _truth.tsv): {len(rows)} SNPs, lambda_gc {lam:.4f}, "
          + ", ".join(f"{c['label']} z {truth[c['label']][3]:.1f}" for c in planted))
    return Path(f"{stem}.tsv")


def _neg(number):
    return number[1:] if number.startswith("-") else "-" + number


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("chip", help="demo chip: every 30th public site plus planted gaps over 1 Mb")
    c.add_argument("--scale", choices=SCALES, default="dev")
    c.add_argument("--seed", type=int, default=SEED)
    g = sub.add_parser("gwas", help="synthetic GWAS summary statistics (5 files) with planted loci and a truth file")
    g.add_argument("--scale", choices=SCALES, default="dev")
    g.add_argument("--seed", type=int, default=SEED)
    g.add_argument("--out", default="data/synthetic", help="output folder (fixture scale: the tests write to a temp folder)")
    args = p.parse_args()
    if args.cmd == "gwas":
        return gwas(SCALES[args.scale][0], args.out, args.scale, seed=args.seed)
    vcf, out_dir, n_gaps, gap_bp = SCALES[args.scale]
    chip(vcf, out_dir, n_gaps, gap_bp, seed=args.seed)


if __name__ == "__main__":
    main()
