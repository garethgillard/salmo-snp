def assay_rows(rel, tmp_path, name="out"):
    f = tmp_path / "SYNTHETIC_assay.tsv"
    f.write_text(SYNTHETIC + "chrom\tpos\tid\tref\talt\n" + "".join(
        f"25\t{p}\t{i}\t{'A' if i == 'mismatch' else 'C'}\t{'G' if i == 'topbot' else 'T'}\n" for p, i in [
            (200, "pass"), (400, "homopolymer"), (600, "gc"), (800, "repeat"), (1000, "n_flank"), (1200, "mismatch"),
            (1400, "topbot"), (3990, "chrom_end")]) + "9\t23837450\tother_chrom\tG\tA\n")
    return {r["id"]: r for r in rows(annotate(f, rel, tmp_path / f"{name}.parquet"))}


# P6.2 assay designability

def test_assay_rules_on_synthetic_sequence(synthetic_release, tmp_path, monkeypatch):
    r = assay_rows(synthetic_release, tmp_path)
    assert r["pass"]["assay_status"] == "pass" and r["pass"]["assay_reasons"] is None
    assert r["pass"]["assay_flank"] == BACKGROUND[164:199] + "[C/T]" + BACKGROUND[200:235]
    assert r["homopolymer"]["assay_homopolymer"] == 10 and r["homopolymer"]["assay_reasons"] == "homopolymer 10"
    assert r["gc"]["assay_gc"] == 1.0 and r["gc"]["assay_status"] == "warn" and r["gc"]["assay_reasons"].startswith("GC 1.0")
    assert r["repeat"]["assay_repeat"] == 1.0 and r["repeat"]["assay_reasons"] == "repeat 1.0"
    assert r["n_flank"]["assay_n"] == 1 and r["n_flank"]["assay_status"] == "fail" and "N in flank" in r["n_flank"]["assay_reasons"]
    # (only A/T and C/G SNPs can mismatch: the other pairs always match a base or its complement)
    assert r["mismatch"]["ref_check"] == "mismatch" and r["mismatch"]["assay_reasons"].startswith("ref mismatch")
    assert r["chrom_end"]["assay_status"] == "fail" and r["chrom_end"]["assay_flank"].endswith("N" * 25)
    assert r["topbot"]["assay_status"] == "warn" and assay.TOPBOT_103 in r["topbot"]["assay_reasons"]
    assert assay.TOPBOT_103 not in (r["chrom_end"]["assay_reasons"] or "")  # C/T is never ambiguous
    assert r["other_chrom"]["assay_status"] == "not_checked" and r["other_chrom"]["assay_flank"] is None
    # Changing a threshold in weights.yaml changes the status counts
    w = yaml.safe_load(WEIGHTS.read_text())
    w["assay"]["max_homopolymer"] = 12
    (tmp_path / "weights.yaml").write_text(yaml.safe_dump(w))
    monkeypatch.setattr(score, "WEIGHTS", tmp_path / "weights.yaml")
    assert assay_rows(synthetic_release, tmp_path, "relaxed")["homopolymer"]["assay_status"] == "pass"


