def rows(path, where="true"):
    rel = duckdb.sql(f"SELECT * FROM read_parquet('{path}') WHERE {where}")
    return [dict(zip(rel.columns, r)) for r in rel.fetchall()]


def write_genome(path, chroms, line=60):
    """A SYNTHETIC soft-masked FASTA, bgzipped in small BGZF blocks with .fai and .gzi, like the real genome."""
    text, fai = b"", []
    for name, seq in chroms.items():
        header = f">{name}\n"
        fai.append(f"{name}\t{len(seq)}\t{len(text) + len(header)}\t{line}\t{line + 1}\n")
        text += (header + "\n".join(seq[i:i + line] for i in range(0, len(seq), line)) + "\n").encode()
    gzi, done = [], 0
    with open(path, "wb") as f:
        for i in range(0, len(text), 1000):
            if i:
                gzi.append((done, i))
            block = bgzf_block(text[i:i + 1000])
            f.write(block)
            done += len(block)
        f.write(bgzf_block(b""))
    Path(f"{path}.fai").write_text("".join(fai))
    Path(f"{path}.gzi").write_bytes(struct.pack("<Q", len(gzi)) + b"".join(struct.pack("<QQ", c, u) for c, u in gzi))


# Planted contexts on a SYNTHETIC chromosome 25 (1-based positions of the SNP; its base is always C)
BACKGROUND = "ACGTTGCAAGCTTCGATCAG" * 200  # GC 0.5, longest run 2


def planted():
    seq = list(BACKGROUND)

    def put(pos, left="", right="", lower=False):
        if left:
            seq[pos - 1 - len(left):pos - 1] = left
        if right:
            seq[pos:pos + len(right)] = right
        seq[pos - 1] = "C"
        if lower:
            seq[pos - 36:pos + 35] = [c.lower() for c in seq[pos - 36:pos + 35]]

    put(200)  # pass
    put(400, right="TTC" + "A" * 10 + "C")  # homopolymer 10
    put(600, left="GC" * 18, right="GC" * 18)  # GC 1.0
    put(800, lower=True)  # soft-masked: repeat 1.0
    put(1000, left="N" + "ACGT" * 2)  # an N 9 bases upstream
    put(1200)  # used with a wrong ref allele
    put(1400, left="AT" * 18, right="AT" * 18)  # a C/G SNP in (AT)n: no TOP/BOT strand (Illumina code 103)
    put(3990)  # near the end: the right flank runs off the chromosome
    return "".join(seq[:4000])


