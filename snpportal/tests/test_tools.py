def test_demo_chip_and_compare(release, annotated, tmp_path):
    out, gaps = make_synthetic.chip(FIXTURE / "12_samples_genotype_filtered_on_504.vcf.gz", tmp_path, 1, 1_100_000)
    assert "SYNTHETIC" in out.name and out.read_text().startswith("# SYNTHETIC test data generated by prep/make_synthetic.py")
    assert out.read_text() == (FIXTURE / "synthetic" / "chip_demo_SYNTHETIC.tsv").read_text()  # same seed, same file
    assert (release / "demo" / "chip_demo_SYNTHETIC.tsv").exists() and (release / "demo" / "known_loci.tsv").exists()
    chip = tmp_path / "chip.parquet"
    assert panel.read_chip(out, release, chip)["snps_kept"] == len(out.read_text().splitlines()) - 3
    sizes = json.loads((release / "manifest.json").read_text())["chrom_sizes"]
    # The planted gap is listed with the best SNP of the list in it; with no list SNPs there, the pool fills it
    (c, start, end), = gaps
    result = panel.compare(annotated["snps.vcf"], chip, "all", chrom_sizes=sizes)
    s = result["summary"]
    assert s["shared"] + s["novel_functional"] + s["other"] == s["total"] == 2519 and s["shared"] > 0
    gap, = [g for g in result["gaps"] if g["chrom"] == c and g["start"] <= start and g["end"] > end]
    assert gap["size"] > 1_000_000 and gap["filler"]["source"] == "list"
    assert all(g["size"] > 1_000_000 for g in result["gaps"])
    lst = tmp_path / "outside.parquet"
    duckdb.sql(f"COPY (SELECT * FROM read_parquet('{annotated['snps.vcf']}') WHERE NOT (chrom = '{c}' AND pos > {gap['start']} "
               f"AND pos < {gap['end']})) TO '{lst}' (FORMAT parquet)")
    result = panel.compare(lst, chip, "all", pool=release / "pool" / "pool.parquet", chrom_sizes=sizes)
    filler = next(g for g in result["gaps"] if g["start"] == gap["start"])["filler"]
    assert filler["source"] == "pool" and gap["start"] < filler["pos"] < gap["end"]
    # The 'not near chip' exclusion changes the panel's candidates
    con = duckdb.connect()
    con.execute(f"CREATE VIEW v AS {panel.compare_sql(f'read_parquet({chr(39)}{lst}{chr(39)})', f'read_parquet({chr(39)}{chip}{chr(39)})', 10000)}")
    near = con.execute("SELECT count(*) FILTER (WHERE near_chip) FROM v").fetchone()[0]
    weights = yaml.safe_load(WEIGHTS.read_text())
    base = panel.design(con, "all", n_target=10, weights=weights, exclude_flags=[])["summary"]["n_candidates"]
    fewer = panel.design(con, "all", n_target=10, weights=weights, exclude_flags=["near_chip"])["summary"]["n_candidates"]
    assert near > 0 and fewer < base


@pytest.mark.dev
@pytest.mark.skipif(__import__("os").environ.get("SNPSCORE_DEV") != "1", reason="needs release/dev (SNPSCORE_DEV=1)")
def test_dev_timings(tmp_path, capsys):
    """public_50k on release/dev: annotate with assay QC, a 384-SNP panel, and the demo chip against the pool."""
    import time
    dev, demo = DATA / "release" / "dev", DATA / "release" / "dev" / "demo"
    t = time.time()
    out = annotate(demo / "public_50k.vcf", dev, tmp_path / "out.parquet", threads=4, memory_limit="4GB")
    t_annotate = time.time() - t
    weights, m = yaml.safe_load(WEIGHTS.read_text()), json.loads((dev / "manifest.json").read_text())
    t = time.time()
    a = panel.design(out, "maturation", n_target=384, weights=weights, chrom_sizes=m["chrom_sizes"])
    t_panel = time.time() - t
    assert a["summary"]["n_selected"] == 384 and panel.design(out, "maturation", n_target=384, weights=weights,
                                                              chrom_sizes=m["chrom_sizes"])["hash"] == a["hash"]
    chip = tmp_path / "chip.parquet"
    panel.read_chip(demo / "chip_demo_SYNTHETIC.tsv", dev, chip)
    planted = [g.split(":") for g in (demo / "chip_demo_SYNTHETIC.tsv").read_text().splitlines()[1].split("(BED): ")[1].split(", ")]
    gaps = panel.compare(out, chip, "maturation", pool=dev / "pool" / "pool.parquet", chrom_sizes=m["chrom_sizes"])["gaps"]
    for c, span in planted:
        s, e = map(int, span.split("-"))
        assert any(g["chrom"] == c and g["start"] <= s and g["end"] > e and g["filler"] for g in gaps)
    con = duckdb.connect()
    status = dict(con.execute(f"SELECT assay_status, count(*) FROM read_parquet('{out}') GROUP BY 1").fetchall())
    reasons = assay.breakdown(con, f"read_parquet('{out}')")
    assert "TOP/BOT cannot be determined" in reasons and "Infinium" in " ".join(a["summary"]["warnings"])
    with capsys.disabled():
        print(f"\npublic_50k: annotate {t_annotate:.1f} s, panel {t_panel:.1f} s, {len(gaps)} chip gaps over 1 Mb; "
              f"assay {status}; reasons {reasons}")
