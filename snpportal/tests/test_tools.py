# P6.3 panel designer

def test_panel_constraints_and_determinism(release, annotated, tmp_path):
    weights = yaml.safe_load(WEIGHTS.read_text())
    sizes = json.loads((release / "manifest.json").read_text())["chrom_sizes"]
    must = rows(annotated["snps.vcf"])[100]["id"]
    kw = dict(n_target=80, min_spacing_bp=10000, max_per_gene=2, max_per_element=1, must_include=[must],
              weights=weights, chrom_sizes=sizes)
    a = panel.design(annotated["snps.vcf"], "maturation", out=tmp_path / "a.parquet", **kw)
    b = panel.design(annotated["snps.vcf"], "maturation", out=tmp_path / "b.parquet", **kw)
    assert a["hash"] == b["hash"]
    assert hashlib.sha256((tmp_path / "a.parquet").read_bytes()).digest() == hashlib.sha256((tmp_path / "b.parquet").read_bytes()).digest()
    picked = rows(tmp_path / "a.parquet")
    s = a["summary"]
    assert must in {r["id"] for r in picked if r["selection_reason"] == "must_include"}
    assert len(picked) == 80 or s["binding"]
    assert all(r["selection_reason"] in ("must_include", "backbone", "functional", "fill") for r in picked)
    assert s["reasons"]["backbone"] and sum(s["reasons"].values()) == len(picked) == s["n_selected"]
    by_chrom = {}
    for r in picked:
        by_chrom.setdefault(r["chrom"], []).append(r["pos"])
    assert all(y - x >= 10000 for p in by_chrom.values() for x, y in zip(sorted(p), sorted(p)[1:]))
    for key, cap in (("gene_id", 2), ("chromatin_id", 1)):
        counts = {}
        for r in picked:
            if r[key]:
                counts[r[key]] = counts.get(r[key], 0) + 1
        assert max(counts.values()) <= cap
    assert all(r["assay_status"] != "fail" and not r["blacklist"] for r in picked  # the design defaults
               if r["selection_reason"] != "must_include")
    # Panel-level vendor checks: Infinium bins (A/T, C/G, others) and the reasons breakdown of the selection
    assert sum(s["infinium_bins"].values()) == len(picked) and any("Infinium" in w for w in s["warnings"])
    assert s["infinium_bins"]["A"] == sum({r["ref"], r["alt"]} == {"A", "T"} for r in picked)
    assert sum(s["assay_reasons"].values()) >= sum(r["assay_status"] in ("warn", "fail", "not_checked") for r in picked)
    # A larger target than the filters allow names the binding constraint
    big = panel.design(annotated["snps.vcf"], "maturation", n_target=5000, weights=weights)
    assert big["summary"]["n_selected"] < 5000 and "filters" in big["summary"]["binding"]


def test_purposes_meet_their_own_constraints(release, annotated, tmp_path):  # I8: weights.yaml design.presets
    weights = yaml.safe_load(WEIGHTS.read_text())
    sizes = json.loads((release / "manifest.json").read_text())["chrom_sizes"]
    assert set(panel.presets(weights)) >= {"genomic_selection", "parentage", "trait"} and 384 in panel.target_sizes(weights)
    for name, preset in panel.presets(weights).items():
        r = panel.design(annotated["snps.vcf"], "all", weights=weights, chrom_sizes=sizes, out=tmp_path / f"{name}.parquet",
                         purpose=name)
        p, s, picked = r["params"], r["summary"], rows(tmp_path / f"{name}.parquet")
        assert s["purpose"] == p["purpose"] == name
        assert all(p[k] == v for k, v in preset.items() if k in panel.DEFAULTS)  # the preset's numbers, as weights.yaml has them
        assert len(picked) == p["n_target"] or s["binding"]
        by_chrom, genes = {}, {}
        for x in picked:
            by_chrom.setdefault(x["chrom"], []).append(x["pos"])
            if x["gene_id"]:
                genes[x["gene_id"]] = genes.get(x["gene_id"], 0) + 1
        assert all(b - a >= p["min_spacing"] for ps in by_chrom.values() for a, b in zip(sorted(ps), sorted(ps)[1:])), name
        assert max(genes.values(), default=0) <= p["max_per_gene"], name
        assert all(x["public_af_maf"] is None or x["public_af_maf"] >= p["min_maf"] for x in picked), name
        if p["require_assay_pass"]:
            assert all(x["assay_status"] == "pass" for x in picked), name
    parentage = rows(tmp_path / "parentage.parquet")
    assert 0 < len(parentage) < len(rows(tmp_path / "trait.parquet"))  # 2 Mb apart on a fixture of a few loci: few markers
    with pytest.raises(panel.InputError):
        panel.design(annotated["snps.vcf"], "all", weights=weights, purpose="nope")


def test_cli_reads_annotate_tsv_and_recomputes_tiers(release, annotated, tmp_path, monkeypatch, capsys):
    """panel, export and compare read annotate's TSV as its parquet (chromosomes as text), and a file's tiers follow
    --preset: annotate output only holds the tiers of the --trait it was annotated with."""
    tsv = annotate(FIXTURE / "snps.vcf", release, tmp_path / "out.tsv")

    def run(*args):
        monkeypatch.setattr(sys, "argv", ["snpportal", *map(str, args)])
        cli.main()
        return capsys.readouterr().out

    run("panel", tsv, "--release", release, "--n", 20, "-o", tmp_path / "p.parquet")
    assert json.loads((tmp_path / "p.summary.json").read_text())["n_selected"] == 20
    written = [run("export", src, "--release", release, "--format", "illumina", "-o", tmp_path / f"x{i}.csv")
               .split(": ")[1].split(" SNPs")[0] for i, src in enumerate((tsv, annotated["snps.vcf"]))]
    assert written[0] == written[1] and int(written[0]) > 0
    chip = FIXTURE / "synthetic" / "chip_demo_SYNTHETIC.tsv"
    on_tsv, on_parquet = (json.loads(run("compare", src, "--chip", chip, "--release", release).splitlines()[0])
                          for src in (tsv, annotated["snps.vcf"]))
    assert on_tsv == on_parquet and on_tsv["total"] == 2519
    with pytest.raises(SystemExit, match="not found"):
        run("panel", tmp_path / "no_such.parquet", "--release", release)
    # The same 'all' annotation designed for two presets: different panels, with the preset's tiers
    weights = yaml.safe_load(WEIGHTS.read_text())
    picks = {p: panel.design(annotated["snps.vcf"], p, n_target=30, weights=weights)["selected"] for p in ("all", "liver")}
    assert [x["row"] for x in picks["all"]] != [x["row"] for x in picks["liver"]]
    liver = rows(annotate(FIXTURE / "snps.vcf", release, tmp_path / "liver.parquet", trait="liver"))
    assert all(x["tier"] == liver[x["row"]]["tier"] for x in picks["liver"])
    # A chip list is read up to a cap: a small .gz could otherwise hold billions of rows
    with pytest.raises(TooMany, match="more than 5"):
        panel.read_chip(chip, release, tmp_path / "chip.parquet", max_snps=5)


def test_export_of_a_view_keeps_row_order(release, annotated, tmp_path, monkeypatch):
    """A connection's view (maybe a join) is written in sorted _row ranges, not one ORDER BY over every wide row."""
    monkeypatch.setattr(sys.modules["snpscore.annotate"], "WRITE_PART", 100)
    con = duckdb.connect()
    con.execute(f"CREATE VIEW v AS SELECT * FROM read_parquet('{annotated['snps.vcf']}', file_row_number=true) ORDER BY random()")
    for fmt in ("tsv", "parquet"):
        export.export(con, fmt, tmp_path / f"view.{fmt}", release, plain=True)
        export.export(annotated["snps.vcf"], fmt, tmp_path / f"file.{fmt}", release, plain=True)
    assert (tmp_path / "view.tsv").read_text() == (tmp_path / "file.tsv").read_text()
    assert rows(tmp_path / "view.parquet") == rows(tmp_path / "file.parquet")
    assert sorted(p.name for p in tmp_path.iterdir()) == ["file.parquet", "file.tsv", "view.parquet", "view.tsv"]


